"""PoC-1: translate the test functions of the guest ELF (binary -> decoder -> function discovery -> C back-end).
Writes build/poc1/rc/poc1_rc.c and poc1_table.h (test order == tests.json order)."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, ROOT)
from ps2rc.image import load_elf  # noqa: E402
from ps2rc.analysis.functions import discover_functions  # noqa: E402
from ps2rc.backend_c import V5_LEVELS, translate_function, fname  # noqa: E402
from ps2rc.analysis.width import argument_livein, narrowing_plan  # noqa: E402

OUT = os.path.join(ROOT, "build", "poc1")


def main():
    meta = json.load(open(os.path.join(OUT, "tests.json")))
    img = load_elf(os.path.join(OUT, "poc1.elf"))
    syms = {s.name: s.value for s in img.symbols if s.name}
    starts = [syms["t_" + t["name"]] for t in meta["tests"]]
    text_end = syms["inputs"]                       # code ends where the data section starts
    fs = discover_functions(img.stripped(), [(0x00100000, text_end)], extra_seeds=starts)
    v5 = next((V5_LEVELS[x[2:]] for x in sys.argv if x[2:] in V5_LEVELS), None)   # --v5s1 .. : v4 + v5 levers
    v4 = v5 is not None or "--v4" in sys.argv
    v3 = v4 or "--v3" in sys.argv
    v2 = v3 or "--v2" in sys.argv
    closure = {a: fs.functions[a] for a in starts}
    plan = narrowing_plan(img, closure, abi=v4, roots=set(starts)) if v2 else {}
    livein = argument_livein(img, closure) if v4 else None
    os.makedirs(os.path.join(OUT, "rc"), exist_ok=True)
    src = ['/* generated by tests/poc1/build_rc.py from poc1.elf - do not edit */', '#include "r5900_rt.h"', ""]
    for a in starts:
        src.append(translate_function(img, a, fs.functions[a].addrs, cache=v2 or "--v1" in sys.argv,
                                      narrow=plan.get(a, frozenset()), fpu_fast=v3, abi=v4, livein=livein, v5=v5))
    open(os.path.join(OUT, "rc", "poc1_rc.c"), "w", newline="\n", encoding="ascii").write("\n".join(src))
    tag = next((x[2:] for x in sys.argv if x.startswith("--v")), "v0")
    tab = ["/* generated */", "#define POC1_NTESTS %d" % len(starts), "#define POC1_NVEC %d" % meta["tests"][0]["nvec"],
           '#define POC1_VARIANT "%s"' % tag]
    tab += ["void %s(R5900Ctx *c);" % fname(a) for a in starts]
    tab.append("static const struct { const char *name; void (*fn)(R5900Ctx *); } poc1_tests[POC1_NTESTS] = {")
    tab += ['    {"%s", %s},' % (t["name"], fname(a)) for t, a in zip(meta["tests"], starts)]
    tab.append("};")
    open(os.path.join(OUT, "rc", "poc1_table.h"), "w", newline="\n", encoding="ascii").write("\n".join(tab) + "\n")
    n = sum(len(fs.functions[a].addrs) for a in starts)
    print("translated %d functions, %d guest instructions" % (len(starts), n))


if __name__ == "__main__":
    main()
