"""VU0 oracle set: translate the test functions of build/poc_vu0/vu0.elf with a C back-end variant.

    python tests/poc_vu0/vu0_build_rc.py v0|v1|v2|v3|v4 [out_dir]

Also checks the assembled guest code first (GNU as misencodes some R5900 instructions): every instruction of every
test function decodes to the mnemonic written in vu0_tests.S (COP2 .word lines: the text in the comment) with the
same GPR operands. Writes <out_dir>/vu0_rc.c and vu0_table.h (test order == tests.json order); default out_dir
build/poc_vu0/rc/<variant>.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, ROOT)
from ps2rc.image import load_elf  # noqa: E402
from ps2rc.analysis.functions import discover_functions  # noqa: E402
from ps2rc.analysis.width import argument_livein, narrowing_plan  # noqa: E402
from ps2rc.backend_c import fname, translate_function  # noqa: E402
from ps2rc.r5900 import decode  # noqa: E402

OUT = os.environ.get("PS2RC_VU0_OUT") or os.path.join(ROOT, "build", "poc_vu0")
PSEUDO = {"move": ("daddu", "addu", "or"), "nop": ("sll",)}


def source_insns():
    """{test name: [(mnemonic, [gpr numbers])]} from vu0_tests.S."""
    tests, cur = {}, None
    for line in open(os.path.join(OUT, "vu0_tests.S"), encoding="ascii"):
        s = line.strip()
        m = re.match(r"t_(\w+):$", s)
        if m:
            cur = tests.setdefault(m.group(1), [])
            continue
        s = re.sub(r"^\d+:\s*", "", s)
        if cur is not None and s.startswith(".word"):
            text = s.split("#", 1)[1].strip()
            cur.append((text.split()[0], None))
            continue
        if cur is None or not s or s.startswith((".", "#")):
            continue
        mnem, _, rest = s.partition(" ")
        cur.append((mnem, [int(x) for x in re.findall(r"\$(\d+)", rest)]))
    return tests


def check_encodings(img, syms, meta):
    src = source_insns()
    for t in meta["tests"]:
        a = syms["t_" + t["name"]]
        for k, (mnem, regs) in enumerate(src[t["name"]]):
            i = decode(img.word(a + 4 * k), a + 4 * k)
            ok = i.mnem == mnem or i.mnem in PSEUDO.get(mnem, ())
            if ok and regs is not None and mnem not in PSEUDO:
                ok = sorted(regs) == sorted(o[1] for o in i.ops if o[0] == "r" or o[0] == "mem")
            if not ok:
                raise SystemExit("guest encoding mismatch in t_%s +%d: wrote %s %s, decoded %s"
                                 % (t["name"], 4 * k, mnem, regs, i.text))


def main():
    variant = sys.argv[1]
    translate(variant, sys.argv[2] if len(sys.argv) > 2 else os.path.join(OUT, "rc", variant))


def translate(variant, out):
    meta = json.load(open(os.path.join(OUT, "tests.json"), encoding="utf-8"))
    img = load_elf(os.path.join(OUT, "vu0.elf"))
    syms = {s.name: s.value for s in img.symbols if s.name}
    check_encodings(img, syms, meta)
    starts = [syms["t_" + t["name"]] for t in meta["tests"]]
    fs = discover_functions(img.stripped(), [(0x00100000, syms["inputs"])], extra_seeds=starts)
    closure = {a: fs.functions[a] for a in starts}
    opts = {}
    if variant != "v0":
        opts = {"cache": True, "fpu_fast": variant in ("v3", "v4"), "abi": variant == "v4"}
    plan = narrowing_plan(img, closure, abi=variant == "v4", roots=set(starts)) if variant in ("v2", "v3", "v4") \
        else {}
    livein = argument_livein(img, closure) if variant == "v4" else None
    os.makedirs(out, exist_ok=True)
    src = ["/* generated by tests/poc_vu0/vu0_build_rc.py from vu0.elf - do not edit */", '#include "r5900_rt.h"', ""]
    for a in starts:
        fn = fs.functions[a]
        jt = {jr: tg for jr, _tab, tg in fn.jump_tables}
        src.append(translate_function(img, a, fn.addrs, jt, set(fs.functions), narrow=plan.get(a, frozenset()),
                                      livein=livein, **opts))
    open(os.path.join(out, "vu0_rc.c"), "w", newline="\n", encoding="ascii").write("\n".join(src))
    tab = ["/* generated */", "#define VU0_NTESTS %d" % len(starts), "#define VU0_NVEC %d" % meta["tests"][0]["nvec"],
           "#define VU0_IN %d" % meta["in_size"], "#define VU0_OUT %d" % meta["out_size"]]
    tab += ["void %s(R5900Ctx *c);" % fname(a) for a in starts]
    tab.append("static const struct { const char *name; void (*fn)(R5900Ctx *); } vu0_tests[VU0_NTESTS] = {")
    tab += ['    {"%s", %s},' % (t["name"], fname(a)) for t, a in zip(meta["tests"], starts)]
    tab.append("};")
    open(os.path.join(out, "vu0_table.h"), "w", newline="\n", encoding="ascii").write("\n".join(tab) + "\n")
    print("%s: translated %d functions, %d guest instructions" % (variant, len(starts),
                                                                  sum(len(fs.functions[a].addrs) for a in starts)))


if __name__ == "__main__":
    main()
