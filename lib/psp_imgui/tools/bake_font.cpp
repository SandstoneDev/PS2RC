// bake_font.cpp - host tool: bakes Dear ImGui's default font (ProggyClean, 13 px, by Tristan Grimmer, MIT) into
// pimgui_font13.h: a 4-bit alpha texture (the PSP GE's T4 format, 16-entry CLUT, low nibble = left texel) and the
// glyph table, so the PSP build needs neither the TTF nor stb_truetype (code + RAM + boot time).
//
//   g++ -O1 -DPIMGUI_HOST -DIMGUI_USER_CONFIG='"pimgui_imconfig.h"' -I.. -I../third_party/imgui bake_font.cpp \
//       ../third_party/imgui/imgui.cpp ../third_party/imgui/imgui_draw.cpp ../third_party/imgui/imgui_widgets.cpp ../third_party/imgui/imgui_tables.cpp -o bake_font
//   ./bake_font > ../pimgui_font13.h          (tools/bake_font.sh does both)
//
// Range: printable ASCII 0x20..0x7E (the menu text); the 2x2 white texel ImGui draws every solid shape with.
#include <stdio.h>
#include <string.h>
#include "imgui.h"
#include "imgui_internal.h"

int main()
{
    ImGui::CreateContext();
    ImFontAtlas *a = ImGui::GetIO().Fonts;
    a->Flags |= ImFontAtlasFlags_NoMouseCursors | ImFontAtlasFlags_NoBakedLines;
    a->TexDesiredWidth = 128;
    static const ImWchar ranges[] = {0x0020, 0x007E, 0};
    ImFontConfig cfg;
    cfg.GlyphRanges = ranges;
    cfg.OversampleH = cfg.OversampleV = 1;            /* what AddFontDefault() does without a template */
    cfg.PixelSnapH = true;
    ImFont *f = a->AddFontDefault(&cfg);
    unsigned char *px;
    int w, h;
    a->GetTexDataAsAlpha8(&px, &w, &h);
    if (w % 32 || h > 512) { fprintf(stderr, "atlas %dx%d not usable as a T4 texture\n", w, h); return 1; }
    printf("/* pimgui_font13.h - GENERATED by tools/bake_font.cpp from Dear ImGui %s's default font: ProggyClean.ttf\n"
           " * 13 px by Tristan Grimmer (MIT licence, http://www.proggyfonts.net), printable ASCII. Do not edit.\n"
           " * Texture: %d x %d texels, 4-bit alpha (GE T4, low nibble = left texel), %d bytes. */\n",
           IMGUI_VERSION, w, h, w * h / 2);
    printf("#define PIMGUI_FONT_TEX_W %d\n#define PIMGUI_FONT_TEX_H %d\n", w, h);
    printf("#define PIMGUI_FONT_SIZE %.1ff\n#define PIMGUI_FONT_ASCENT %.1ff\n#define PIMGUI_FONT_DESCENT %.1ff\n",
           f->FontSize, f->Ascent, f->Descent);
    printf("#define PIMGUI_FONT_WHITE_U %.8ff\n#define PIMGUI_FONT_WHITE_V %.8ff\n", a->TexUvWhitePixel.x,
           a->TexUvWhitePixel.y);
    printf("static const unsigned char pimgui_font_t4[%d] __attribute__((aligned(16))) = {", w * h / 2);
    int n = 0, levels = 0;
    for (int i = 0; i < w * h; i += 2) {
        unsigned lo = (px[i] + 8) / 17, hi = (px[i + 1] + 8) / 17;   /* 0..255 -> 0..15 */
        if (px[i] && px[i] != 255) levels++;
        printf("%s0x%02x,", n++ % 16 ? "" : "\n", lo | hi << 4);
    }
    printf("\n};\n");
    /* glyphs as built (the tab glyph is added again by ImFont::BuildLookupTable at run time) */
    printf("/* codepoint, advance_x, x0, y0, x1, y1, u0, v0, u1, v1 */\nstatic const float pimgui_font_glyphs[][10] = {\n");
    int ng = 0;
    for (int i = 0; i < f->Glyphs.Size; i++) {
        const ImFontGlyph &g = f->Glyphs[i];
        if (g.Codepoint == '\t') continue;
        printf("{%u,%g,%g,%g,%g,%g,%.8ff,%.8ff,%.8ff,%.8ff},\n", g.Codepoint, g.AdvanceX, g.X0, g.Y0, g.X1, g.Y1, g.U0,
               g.V0, g.U1, g.V1);
        ng++;
    }
    printf("};\n#define PIMGUI_FONT_GLYPHS %d\n", ng);
    fprintf(stderr, "baked %d glyphs, %dx%d, %d partial-alpha texels\n", ng, w, h, levels);
    ImGui::DestroyContext();
    return 0;
}
