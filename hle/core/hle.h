/* hle.h - the HLE runtime around a statically recompiled PS2 program (PS2 EE -> C), host and PSP.
 *
 * The generated code runs unchanged; this layer provides what the PS2 provides around it: the EE kernel (threads,
 * semaphores, interrupts, alarms - hle_sched.c and hle_syscall.c), the hardware the program touches directly
 * (hle_mmio.c), and high-level replacements ("hooks") for Sony library functions and IOP services (hle_sce.c,
 * hle_iop.c). The game pack adds its own modules through the interface below ("the game pack's interface").
 * Everything OS-specific is behind hle_plat.h (host: hle/host/hle_host.c, PSP: hle/psp/hle_psp.c).
 *
 * Hooks: a guest function listed in the pack's hooks.def is renamed fn_XXXXXXXX__guest in the generated sources by
 * ps2rc/pipeline/prepare_gen.py; every call to fn_XXXXXXXX (direct calls in any unit and the JALR dispatch table)
 * then reaches the HLE definition, HLE_FN(name) / HLE_SCE(name). The original stays callable as GUEST_FN(name).
 */
