/* ------------------------------------------------------------------ guest memory map (EE RAM) */
#define HLE_RAM_SIZE      0x02000000u     /* EE address space of RAM (32 MB): address mask = HLE_RAM_SIZE - 1 */
extern uint32_t hle_ram_end;              /* end of the guest RAM actually present: 32 MB on the host, the pack's
                                             HLE_PACK_RAM_END_PSP on the PSP (and with the host's --psp-layout) */
#define HLE_KERNEL_BASE   0x00080000u     /* 0x80000-0xFFFFF: HLE kernel area (the real EE kernel lives below 0x100000;
                                             the game never touches it) */
#define HLE_INTR_STACK_TOP 0x000F0000u    /* interrupt-context guest stack (64 KB below) */
#define HLE_FAKE_SERVER   0x000F8000u     /* fake SIF RPC server records (one 64-byte record per bound client) */
#define HLE_SPR_SIZE      0x4000u
/* guest code region (the pack's [memory] code): never read or written as data by the program; the PSP does not load
   it and uses that host memory for its own buffers ("the hole") */
#define HLE_CODE_LO       HLE_PACK_CODE_LO
#define HLE_CODE_HI       HLE_PACK_CODE_HI
#define HLE_DATA_END      HLE_PACK_DATA_END     /* end of the ELF's file data */
#define HLE_BSS_END       HLE_PACK_BSS_END      /* end of BSS incl. an overlay buffer (_end) */

