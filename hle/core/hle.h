/* ------------------------------------------------------------------ threads / scheduler (hle_sched.c) */
#define HLE_MAX_THREADS 64
#define HLE_MAX_SEMAS 256
enum { TS_FREE = 0, TS_DORMANT, TS_READY, TS_RUN, TS_WAIT };          /* + suspend flag */
enum { WK_NONE = 0, WK_SLEEP, WK_SEMA, WK_DELAY, WK_VSYNC };

typedef struct HleThread {
    R5900Ctx c;                     /* MUST stay first: generated code receives &t->c */
    int id, status, suspended;
    int wait_kind, wait_id;
    int prio, init_prio;
    uint32_t entry, stack, stack_size, gp, attr, option, arg;
    int wakeup_count;
    int intr_disabled;              /* guest Status.EIE cleared (DI) while this thread runs */
    uint64_t delay_until;           /* WK_DELAY */
    int sema_result;                /* WaitSema return value set by the waker (0 or deleted) */
    hle_hostctx hc;                 /* host context (coroutine) */
    void *host_stack;
    size_t host_stack_size;
    int host_started;               /* host context created for the current incarnation */
    struct HleThread *next;         /* ready queue / sema wait queue link */
    uint64_t run_count;
} HleThread;

