/* hle_splash.c - the community QR splash of the main PSP build.
 *
 * Shown once per boot by game_main (psp/hle_psp.c) after the configuration is read and before the guest RAM window is
 * allocated - nothing else uses the screen yet (the GE is started later, in hle_boot_init), the intro movies come
 * after it. It always waits for a button: there is no run option for it. The only switch is
 * the BUILD: mk/build.sh SPLASH=1 compiles this unit in (-DHLE_SPLASH); without -DHLE_SPLASH it compiles to
 * an empty object and hle_psp.c contains no call (SPLASH=0 = exactly the build without the splash).
 *
 * Picture (480x272, 8888, drawn by the CPU one scanline at a time into VRAM 0x88000 - the debug console keeps VRAM
 * 0..0x88000 - and shown with sceDisplaySetFrameBuf; the debug console is shown again afterwards): background gradient,
 * on the left the white QR panel (the community invite https://discord.gg/wV8x46ZTDu, a 29x29 matrix, 6 px modules +
 * the 4-module quiet zone), on the right the anti-aliased English text
 *   "Join the / Sandstone_PSP / community", "Scan the QR code to join", "Recompiler author: / SandstoneDev",
 *   "Press any button to continue" (dim for the first SPL_MIN_MS, then pulsing).
 * The text lines are 4-bit alpha bitmaps rendered once from DejaVu Sans by tools/dev/splash_gen.py, which writes the
 * GENERATED block below (and previews that use this file's integer arithmetic).
 *
 * Input: any of the 12 user buttons skips, but only after SPL_MIN_MS (1.5 s) AND after every button was released once
 * in that time - a button still held from the XMB never skips it. HOME -> Exit still works: the exit callback (hle_psp.c)
 * sets hle_exit_requested, the splash returns 1 and game_main ends the run through the normal exit sequence.
 * Log (session.log): one line when it is shown, one when it is dismissed (buttons, time, frames) or left through HOME.
 *
 * Test variant (emulator checks ONLY, never a package): build.sh SPLASH=test adds -DHLE_SPLASH_AUTOPRESS - in
 * an emulator (kemulator: devctl) the splash writes its frame to <EBOOT dir>/splash_test.bmp and presses a button by
 * itself 0.3 s after the minimum time (with a file splash_test_home next to the EBOOT it takes the HOME -> Exit path
 * instead, as the exit callback would); on a real PSP even that build waits for a real button. */
