#define SPL_MIN_MS 1500u                       /* shown at least this long before a button counts */
#define SPL_PULSE_MS 1200u                     /* the prompt's pulse period once a button counts */
#define SPL_VRAM_OFF 0x88000u                  /* 8888, stride 512: 512 x 272 x 4 bytes from VRAM + 0x88000 (the GE
                                                  is not up yet) */
#define SPL_STRIDE 512
#define SPL_KEYS (PSP_CTRL_SELECT | PSP_CTRL_START | PSP_CTRL_UP | PSP_CTRL_RIGHT | PSP_CTRL_DOWN | PSP_CTRL_LEFT | \
                  PSP_CTRL_LTRIGGER | PSP_CTRL_RTRIGGER | PSP_CTRL_TRIANGLE | PSP_CTRL_CIRCLE | PSP_CTRL_CROSS | \
                  PSP_CTRL_SQUARE)

int hle_psp_is_emulator(void);                 /* psp/hle_prof_psp.c */

static inline uint32_t spl_pix(unsigned r, unsigned g, unsigned b) { return 0xFF000000u | b << 16 | g << 8 | r; }

static int spl_qr_dark(int mx, int my)
{
    int n = spl_qr[0], stride = (n + 7) / 8;
    if (mx < 0 || my < 0 || mx >= n || my >= n) return 0;
    return (spl_qr[1 + my * stride + (mx >> 3)] >> (7 - (mx & 7))) & 1;
}

/* one scanline (the arithmetic of ad_splash_gen.py render(): a dump of the test build equals its preview) */
static void spl_row(volatile uint32_t *dst, int y, int lvl)
{
    uint32_t line[SPL_W];
    unsigned t = SPL_BG_TOP, b = SPL_BG_BOT, k = SPL_H - 1;
    unsigned r = ((t >> 16 & 255) * (k - y) + (b >> 16 & 255) * y) / k;
    unsigned g = ((t >> 8 & 255) * (k - y) + (b >> 8 & 255) * y) / k;
    unsigned bl = ((t & 255) * (k - y) + (b & 255) * y) / k;
    uint32_t bg = spl_pix(r, g, bl);
    for (int x = 0; x < SPL_W; x++) line[x] = bg;
    int n = spl_qr[0], panel = (n + 2 * SPL_QUIET) * SPL_MOD;
    if (y >= SPL_PY && y < SPL_PY + panel) {
        int my = (y - SPL_PY) / SPL_MOD - SPL_QUIET;
        for (int x = SPL_PX; x < SPL_PX + panel; x++)
            line[x] = spl_qr_dark((x - SPL_PX) / SPL_MOD - SPL_QUIET, my) ? 0xFF000000u : 0xFFFFFFFFu;
    }
    if (y >= SPL_DIV_Y && y < SPL_DIV_Y + SPL_DIV_H) {
        uint32_t d = spl_pix(SPL_DIV_RGB >> 16 & 255, SPL_DIV_RGB >> 8 & 255, SPL_DIV_RGB & 255);
        for (int x = SPL_DIV_X; x < SPL_DIV_X + SPL_DIV_W; x++) line[x] = d;
    }
    for (int i = 0; i < SPL_NITEMS; i++) {
        const SplItem *it = &spl_items[i];
        if (y < it->y || y >= it->y + it->h) continue;
        unsigned level = i == SPL_PROMPT ? (unsigned)lvl : 256u;
        unsigned fr = it->rgb >> 16 & 255, fg = it->rgb >> 8 & 255, fb = it->rgb & 255;
        const unsigned char *row = spl_alpha + it->off + (unsigned)(y - it->y) * (unsigned)((it->w + 1) / 2);
        for (int c = 0; c < it->w; c++) {
            unsigned a = (unsigned)(c & 1 ? row[c >> 1] & 15 : row[c >> 1] >> 4) * 17u;
            if (!a) continue;
            a = (a * level + 128u) >> 8;
            uint32_t p = line[it->x + c];
            unsigned pr = p & 255, pg = p >> 8 & 255, pb = p >> 16 & 255;
            line[it->x + c] = spl_pix((pr * (255u - a) + fr * a + 127u) / 255u, (pg * (255u - a) + fg * a + 127u) / 255u,
                                      (pb * (255u - a) + fb * a + 127u) / 255u);
        }
    }
    for (int x = 0; x < SPL_W; x++) dst[x] = line[x];
}

/* the prompt's level: dim until a button counts, then a triangle pulse between 110/256 and full */
static int spl_level(unsigned ms)
{
    if (ms < SPL_MIN_MS) return SPL_LVL_DIM;
    unsigned ph = (ms - SPL_MIN_MS) % SPL_PULSE_MS, half = SPL_PULSE_MS / 2;
    unsigned tri = ph < half ? half - ph : ph - half;                /* starts at full brightness */
    return 110 + (int)(tri * 146u / half);
}

