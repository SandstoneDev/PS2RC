/* returns 0 = dismissed by a button, 1 = HOME -> Exit was chosen while it was shown */
int hle_splash_show(const char *dir)
{
    (void)dir;
    uintptr_t edram = (uintptr_t)sceGeEdramGetAddr();
    void *fb = (void *)((edram + SPL_VRAM_OFF) | 0x40000000u);       /* uncached, like the debug console's */
    volatile uint32_t *vr = (volatile uint32_t *)fb;
    int n = spl_qr[0];
    LOG("splash: community QR splash (build switch SPLASH=1): QR %dx%d = %s; \"%s %s %s\", \"%s\", \"%s %s\", "
        "\"%s\"; any button after %u ms (HOME still exits)\n", n, n, SPL_QR_URL, spl_text[0], spl_text[1], spl_text[2],
        spl_text[3], spl_text[4], spl_text[5], spl_text[SPL_PROMPT], SPL_MIN_MS);
    SceInt64 t0 = sceKernelGetSystemTimeWide();
    for (int y = 0; y < SPL_H; y++) spl_row(vr + y * SPL_STRIDE, y, SPL_LVL_DIM);
    unsigned draw_us = (unsigned)(sceKernelGetSystemTimeWide() - t0);
    sceDisplaySetFrameBuf(fb, SPL_STRIDE, PSP_DISPLAY_PIXEL_FORMAT_8888, PSP_DISPLAY_SETBUF_NEXTFRAME);
    LOG("splash: shown (VRAM %06x, 480x272 8888, drawn in %u us) - waiting for a button\n", SPL_VRAM_OFF, draw_us);
    int autopress = 0;
#ifdef HLE_SPLASH_AUTOPRESS
    int autohome = 0;
    autopress = hle_psp_is_emulator();
    if (autopress) {                         /* a file splash_test_home next to the EBOOT: the HOME -> Exit path */
        char hp[320];
        SceIoStat st;
        snprintf(hp, sizeof hp, "%ssplash_test_home", dir);
        autohome = sceIoGetstat(hp, &st) >= 0;
    }
    LOG("splash: TEST BUILD (HLE_SPLASH_AUTOPRESS) - %s\n", autohome ? "emulator: frame dump + simulated HOME -> Exit"
        : autopress ? "emulator: frame dump + automatic press" : "not an emulator: waits for a real button");
    if (autopress) spl_dump(dir, vr);
    if (autohome) autopress = 0;
#endif
    const SplItem *pr = &spl_items[SPL_PROMPT];
    int armed = 0, frames = 0, lvl_shown = SPL_LVL_DIM, home = 0;
    uint32_t pressed = 0, held_at_start = 0;
    unsigned ms = 0;
    for (;;) {
        sceDisplayWaitVblankStart();
        frames++;
        ms = (unsigned)((sceKernelGetSystemTimeWide() - t0) / 1000);
#ifdef HLE_SPLASH_AUTOPRESS
        if (autohome && ms >= SPL_MIN_MS + 300u) hle_exit_requested = 1;   /* what the exit callback does on HOME */
#endif
        if (hle_exit_requested) { home = 1; break; }
        int lvl = spl_level(ms);
        if (lvl != lvl_shown) {                                    /* only the prompt's rows change */
            for (int y = pr->y; y < pr->y + pr->h; y++) spl_row(vr + y * SPL_STRIDE, y, lvl);
            lvl_shown = lvl;
        }
        SceCtrlData pad;
        memset(&pad, 0, sizeof pad);
        sceCtrlPeekBufferPositive(&pad, 1);
        uint32_t b = pad.Buttons & SPL_KEYS;
        if (autopress && ms >= SPL_MIN_MS + 300u) b = ms >= SPL_MIN_MS + 500u ? PSP_CTRL_CROSS : 0u;
        if (frames == 1) held_at_start = b;
        if (ms < SPL_MIN_MS) continue;
        if (!armed) { armed = b == 0; continue; }                  /* every button released once first */
        if (b) { pressed = b; break; }
    }
    void *con = (void *)(edram | 0x40000000u);                     /* the debug console again (VRAM 0, 8888) */
    sceDisplaySetFrameBuf(con, SPL_STRIDE, PSP_DISPLAY_PIXEL_FORMAT_8888, PSP_DISPLAY_SETBUF_NEXTFRAME);
    sceDisplayWaitVblankStart();
    if (home)
        LOG("splash: HOME -> Exit chosen while the splash was shown (%u ms, %d frames)\n", ms, frames);
    else
        LOG("splash: dismissed by %s (buttons %04x) after %u ms, %d frames%s\n",
            autopress ? "the TEST auto-press (HLE_SPLASH_AUTOPRESS)" : "a button press", (unsigned)pressed, ms, frames,
            held_at_start ? " (a button was held when it appeared: waited for its release)" : "");
    return home;
}
