Y_CA_V_NEW = """VU0_INLINE uint32_t vu0_clamp(uint32_t x)          /* lever "ca": = f_in5 (the f_in mapping) */
{
    return f_in5(x);
}"""


Y_GCTX_OLD = "} R5900Ctx;\n"
Y_GCTX_NEW = """} R5900Ctx;

/* lever "gctx" (needs a text transform of the generated units into bodies NAME__g): in the generated units (compiled
   with -DRT_GCTX) the context pointer `c` and the RAM base `rt_gram` are global register variables in callee-saved
   registers - every other unit (HLE, libc) preserves them. The generated bodies NAME__g(void) use them; the C-ABI entry
   NAME(R5900Ctx *) of every body (RT_GCTX_THUNK) loads both from its argument around the body and restores them. */
#ifdef RT_GCTX
#if defined(__mips__)
register R5900Ctx *c __asm__("$23");          /* s7 */
register uint8_t *rt_gram __asm__("$22");     /* s6 */
#elif defined(__x86_64__)
register R5900Ctx *c __asm__("r15");
register uint8_t *rt_gram __asm__("r14");
#else
#error "RT_GCTX: no register assignment for this target"
#endif
/* the C-ABI entry of a body: a tail call of the one shared entry (defined by the transform in <unit>_tab.c), which
   saves both registers, loads them from the argument, runs the body and restores them */
void rt_gctx_call(R5900Ctx *a, void (*body)(void));
#define RT_GCTX_THUNK(n) void n(R5900Ctx *a_) { rt_gctx_call(a_, n##__g); }
/* JALR inside the generated code: main-program bodies straight from a cache, everything else (overlay window, hooks,
   zone wrappers, unknown targets) through the HLE's rc_dispatch and the C-ABI entries */
void rc_gdispatch(uint32_t a);
#endif
"""


def patch_y(text, levers, mode):
    """The runtime-header speed levers on the patched header text."""
    for lv in levers:
        if lv not in Y_LEVERS:
            raise SystemExit("patch_rt_header: unknown --y lever %s (%s)" % (lv, ", ".join(Y_LEVERS)))
    if "mb" in levers:
        levers = list(levers) + ["mbk", "mbb"]
    if "mbk" in levers and "mbb" not in levers:          # measurement step: constant mask only
        if text.count(Y_MB_OLD) != 1:
            raise SystemExit("patch_rt_header: --y mbk: RMB_PTR not found exactly once")
        text = text.replace(Y_MB_OLD, Y_MB_OLD.replace("(m).mask", "0x01FFFFFFu"))
    if "mbb" in levers and "mbk" not in levers:          # measurement step: asm base only
        if text.count(Y_MB_OLD) != 1:
            raise SystemExit("patch_rt_header: --y mbb: RMB_PTR not found exactly once")
        text = text.replace(Y_MB_OLD, Y_MB_NEW.replace("(b & RT_Y_MASK)", "(b & m.mask)"))
    if "mbk" in levers and "mbb" in levers:
        if mode == "host":
            raise SystemExit("patch_rt_header: --y mb needs --mode psp|check")
        for old, new in ((Y_MB_OLD, Y_MB_NEW), (Y_RM_OLD, Y_RM_NEW)):
            if text.count(old) != 1:
                raise SystemExit("patch_rt_header: --y mb: %r not found exactly once" % old)
            text = text.replace(old, new)
        if mode == "check":
            if text.count(Y_MBCHK_OLD) != 1:
                raise SystemExit("patch_rt_header: --y mb: RMB_CHECK rmb_ptr not found")
            text = text.replace(Y_MBCHK_OLD, Y_MBCHK_NEW)
    if "ca" in levers:
        if mode != "psp":
            raise SystemExit("patch_rt_header: --y ca is Allegrex code (--mode psp only)")
        for old, new in ((Y_CA_F_OLD, Y_CA_F_NEW), (Y_CA_V_OLD, Y_CA_V_NEW)):
            if text.count(old) != 1:
                raise SystemExit("patch_rt_header: --y ca: %r not found exactly once" % old.split("\n")[0])
            text = text.replace(old, new)
    if "ca2" in levers:
        if mode != "psp" or "ca" in levers:
            raise SystemExit("patch_rt_header: --y ca2 is Allegrex code (--mode psp only) and excludes ca")
        for old, new in ((Y_CA_F_OLD, Y_CA2_F_NEW), (Y_CA_V_OLD, Y_CA_V_NEW.replace('lever "ca"', 'lever "ca2"'))):
            if text.count(old) != 1:
                raise SystemExit("patch_rt_header: --y ca2: %r not found exactly once" % old.split("\n")[0])
            text = text.replace(old, new)
    if "be" in levers:
        if text.count(Y_BE_OLD) != 1:
            raise SystemExit("patch_rt_header: --y be: RC_BACKEDGE_AT not found exactly once")
        text = text.replace(Y_BE_OLD, Y_BE_NEW)
    if "gctx" in levers or "gctx1" in levers:            # needs the NAME__g transform of the generated units
        if "gctx" in levers and "gctx1" in levers:
            raise SystemExit("patch_rt_header: --y gctx and gctx1 exclude each other")
        if text.count(Y_GCTX_OLD) != 1:
            raise SystemExit("patch_rt_header: --y gctx: the R5900Ctx typedef end not found exactly once")
        new = Y_GCTX_NEW
        if "gctx1" in levers:                            # gctx1: only c in a register (s7 / r15); rt_gram = c->ram
            for a, b in (('register uint8_t *rt_gram __asm__("$22");     /* s6 */\n', ""),
                         ('register uint8_t *rt_gram __asm__("r14");\n', ""),
                         ("#ifdef RT_GCTX\n", "#ifdef RT_GCTX\n#define RT_GCTX1 1    /* lever gctx1: the context pointer only */\n"
                                              "#define rt_gram (c->ram)\n")):
                assert new.count(a) == 1, a
                new = new.replace(a, b)
        text = text.replace(Y_GCTX_OLD, new)
    return text


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    mode = sys.argv[sys.argv.index("--mode") + 1] if "--mode" in sys.argv else "host"
    alias = sys.argv[sys.argv.index("--alias") + 1] if "--alias" in sys.argv else "inline"
    maskbase = "--maskbase" in sys.argv
    ylev = sys.argv[sys.argv.index("--y") + 1] if "--y" in sys.argv else ""
    if "--mode" in sys.argv:
        args = [a for a in args if a != mode]
    if "--alias" in sys.argv:
        args = [a for a in args if a != alias]
    if "--y" in sys.argv:
        args = [a for a in args if a != ylev]
    src = args[0] if len(args) > 0 else os.path.join(ROOT, "runtime", "r5900_rt.h")
    dst = args[1] if len(args) > 1 else os.path.join(ROOT, "build", "rt", "r5900_rt.h")
    text = patch(open(src, encoding="utf-8").read(), mode, alias, maskbase)
    if ylev:
        text = patch_y(text, [x for x in ylev.split(",") if x], mode)
    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    old = open(dst, encoding="utf-8").read() if os.path.exists(dst) else None
    if old != text:
        open(dst, "w", encoding="utf-8", newline="\n").write(text)
    print("patch_rt_header (%s%s%s%s): %s -> %s%s" % (mode, "" if alias == "inline" else ", alias call",
                                                     ", maskbase" if maskbase else "", ", y " + ylev if ylev else "",
                                                     src, dst, "" if old != text else " (unchanged)"))


if __name__ == "__main__":
    main()
