"""PoC-6: derive the harness-local runtime header from src/runtime/r5900_rt.h (which the back-end owners keep
extending) by applying a PoC-6 delta.

    python ps2rc/pipeline/patch_rt_header.py [in=runtime/r5900_rt.h] [out=build/rt/r5900_rt.h] [--mode MODE]
                                         [--alias inline|call] [--maskbase]

MODE host (default; the host v0 harness): the guest memory accessors trap every address outside the 32 MB RAM window
    into the harness (src/hle/hle_mmio.c) instead of masking it into RAM.
MODE psp (the PSP build, tests/phase6psp): the original masked accessors stay (code size: one AND per access; the
    scratchpad and the RAM mirrors alias correctly through the mask); trapping variants rtx_* / rmx_* are added, which
    tests/poc6/prepare_gen.py --trapset substitutes in the few functions that touch hardware registers.
MODE check (host build of the PSP configuration): as psp, but every plain accessor first checks that its address is
    RAM, a RAM mirror or the scratchpad and reports anything else (hle_alias_check in src/hle/hle_host.c): a hardware
    access outside the trap set shows up on the host before it silently aliases into low RAM on the PSP.

tests/poc6/build.sh runs it for every build (output in the WSL build dir), so the harness always compiles against the
current original plus this delta; the copy in src/hle/rt/ is the reference for the later merge (regenerate it with
the default arguments). Fails loudly when an accessor it must replace is not found exactly once.

--alias (psp / check modes): `inline` (the default) resolves the scratchpad and the uncached RAM mirrors inside every
    trapping accessor (RTX_ALIAS); `call`: one out-of-line call to hle_mem_* for every non-RAM address
    (hle/core/hle_mmio.c serves the scratchpad and the mirrors first, before its profiler scope). On the PSP-3000 the
    inline form cost +284 KB of code and made almost every zone slower (I-cache).
--maskbase (psp / check): for a back-end v5s4 translation (rmb_<op>(m, base, offset) accessors):
    adds the trapping rmbx_* (= rmx_* of base + offset; ps2rc/pipeline/prepare_gen.py rewrites rmb_ in the trap set) and,
    in check mode, the hardware-address check in the plain rmb_* accessors. Without it the output is unchanged.
"""
