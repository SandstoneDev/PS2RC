def _trapping_variant(key, alias="inline"):
    """rtx_* / rmx_* definition from the host-mode accessor text. rmx_* take the context as well (prepare_gen passes
    the generated function's `c`), so a trapped register access is a safe point like in the host v0 harness.
    alias "inline" (build 24): + the inline scratchpad / mirror resolution; "call" (build 23 / 25): without it."""
    t = ACC[key]
    t = re.sub(r"\b(r[tm])_((?:l|s)[bhwdq])\(", r"\1x_\2(", t)
    t = t.replace("RT_FAST(a)", "RT_FASTX(a)").replace("RT_PTR(", "RTX_PTR(").replace("RT_AL(", "RTX_AL(")
    t = t.replace("RM_PTR(", "RMX_PTR(").replace("RM_AL(", "RMX_AL(")
    if key.startswith("rm_"):
        t = t.replace("(R5900Mem m, ", "(R5900Ctx *c, R5900Mem m, ")
        t = re.sub(r"\b(hle_mem_(?:read|write)(?:128)?)\(0, ", r"\1(c, ", t)
    return _with_alias(key, t) if alias == "inline" else t


RMB_SIG = {"lb": ("uint8_t ", "", ""), "lh": ("uint16_t", "", ""), "lw": ("uint32_t", "", ""),
           "ld": ("uint64_t", "", ""), "sb": ("void", ", uint8_t v", ", v"), "sh": ("void", ", uint16_t v", ", v"),
           "sw": ("void", ", uint32_t v", ", v"), "sd": ("void", ", uint64_t v", ", v"),
           "lq": ("void", ", R5900Reg128 *d", ", d"), "sq": ("void", ", const R5900Reg128 *s", ", s")}


def _rmb_trapping(key):
    """rmbx_* for back-end v5s4 (maskbase: rmb_<op>(m, base, offset, ...)) in the trap set - the
    trapping accessor of the full guest address base + offset, i.e. exactly rmx_* (v4 semantics: RAM below
    hle_ram_end, everything else to hle_mem_*), so a trap-set function behaves as with v5s3."""
    op = key[4:]
    ret, params, args = RMB_SIG[op]
    return ("static inline %s rmbx_%s(R5900Ctx *c, R5900Mem m, uint32_t b, int32_t o%s) { %srmx_%s(c, m, b + "
            "(uint32_t)o%s); }" % (ret, op, params, "" if ret == "void" else "return ", op, args))


ALIAS_SIZE = {"lb": (1, "uint8_t"), "lh": (2, "uint16_t"), "lw": (4, "uint32_t"), "ld": (8, "uint64_t"),
              "sb": (1, "uint8_t"), "sh": (2, "uint16_t"), "sw": (4, "uint32_t"), "sd": (8, "uint64_t")}


def _with_alias(key, t):
    """build 24: put the inline scratchpad / RAM-mirror resolution (RTX_ALIAS) in front of the slow hle_mem_* call."""
    op = key[3:]
    rt = key.startswith("rt_")
    n_al = 16 if op in ("lq", "sq") else ALIAS_SIZE[op][0]
    if n_al == 1:
        ptr = "RTX_PTR(c, o_)" if rt else "RMX_PTR(m, o_)"
    else:                                            # aligned guest accesses: o_ keeps the alignment of a
        ptr = ("RTX_AL(c, o_, %d)" if rt else "RMX_AL(m, o_, %d)") % n_al
    if op == "lq":
        old = "else hle_mem_read128(c, a & ~15u, d);"
        new = ("else { uint32_t o_ = RTX_ALIAS(a & ~15u); if (o_ != 0xFFFFFFFFu) memcpy(d, %s, 16); "
               "else hle_mem_read128(c, a & ~15u, d); }" % ptr)
    elif op == "sq":
        old = "else hle_mem_write128(c, a & ~15u, s);"
        new = ("else { uint32_t o_ = RTX_ALIAS(a & ~15u); if (o_ != 0xFFFFFFFFu) memcpy(%s, s, 16); "
               "else hle_mem_write128(c, a & ~15u, s); }" % ptr)
    elif op[0] == "l":
        n, ty = ALIAS_SIZE[op]
        m = re.search(r"return (\([\w ]+\))?hle_mem_read\(c, a, %d\);" % n, t)
        assert m, (key, t)
        old = m.group(0)
        new = ("{ uint32_t o_ = RTX_ALIAS(a); if (o_ != 0xFFFFFFFFu) { %s v_; memcpy(&v_, %s, %d); return v_; } } %s"
               % (ty, ptr, n, old))
    else:
        n, ty = ALIAS_SIZE[op]
        old = "else hle_mem_write(c, a, %d, v);" % n
        new = ("else { uint32_t o_ = RTX_ALIAS(a); if (o_ != 0xFFFFFFFFu) { %s v_ = v; memcpy(%s, &v_, %d); } "
               "else hle_mem_write(c, a, %d, v); }" % (ty, ptr, n, n))
    assert t.count(old) == 1, (key, old, t)
    return t.replace(old, new)


def patch(text, mode="host", alias="inline", maskbase=False):
    if mode not in ("host", "psp", "check"):
        raise SystemExit("patch_rt_header: unknown mode %s" % mode)
    if alias not in ("inline", "call"):
        raise SystemExit("patch_rt_header: unknown --alias %s (inline | call)" % alias)
    lines = text.split("\n")
    out, hits = [], {k: 0 for k in ACC}
    rmb_hits = []
    note_done = protos_done = False
    for ln in lines:
        if not note_done and ln.strip() == "*/":
            if mode == "host":
                out.append(NOTE.rstrip("\n"))
            else:
                out.append((NOTE_PSP % (mode, " (check mode: each first reports non-RAM addresses)"
                                        if mode == "check" else "")).rstrip("\n"))
            out.append(ln)
            note_done = True
            continue
        key = None
        m = re.match(r"#define (RT_PTR|RM_PTR)\(", ln)
        if m:
            key = m.group(1)
        else:
            m = re.match(r"static inline [\w ]+?\b(r[tm]_(?:l|s)[bhwdq])\(", ln)
            if m and m.group(1) in ACC:
                key = m.group(1)
        if key:
            hits[key] += 1
            if mode == "host":
                if key == "RT_PTR" and not protos_done:
                    out.append(PROTOS.rstrip("\n"))
                    protos_done = True
                out.append(ACC[key])
                continue
            if key == "RT_PTR" and not protos_done:
                out.append(PSP_DELTA.rstrip("\n"))
                if mode == "check":
                    out.append(CHECK_MACRO)
                protos_done = True
            if mode == "check" and not key.endswith("_PTR"):
                ln = ln.replace("{", "{ RT_CHK(a);", 1)          # one-line definitions: check first
            out.append(ln)
            continue
        m = re.match(r"static inline [\w ]+?\b(rmb_(?:l|s)[bhwdq])\(R5900Mem m, uint32_t b, int32_t o", ln)
        if m and mode != "host" and maskbase:            # back-end v5s4 (maskbase) accessors
            rmb_hits.append(m.group(1))
            if mode == "check":
                ln = ln.replace("{", "{ RT_CHK(b + (uint32_t)o);", 1)
        out.append(ln)
    bad = [k for k, n in hits.items() if n != 1 and not (n == 0 and k in OPTIONAL)]
    if bad or not note_done:
        raise SystemExit("patch_rt_header: accessors not found exactly once in the original: %s" % ", ".join(bad))
    if mode != "host":                                   # trapping variants after the last original accessor
        text_out = "\n".join(out)
        extra = "\n".join(_trapping_variant(k, alias) for k in ACC if not k.endswith("_PTR") and hits[k] == 1)
        extra += "".join("\n" + _rmb_trapping(k) for k in rmb_hits if "rm_" + k[4:] in ACC and hits["rm_" + k[4:]] == 1)
        anchor = text_out.rfind("\n#endif")
        return text_out[:anchor] + "\n/* PoC-6 PSP delta: trapping accessors (trap-set functions only) */\n" + \
            extra + "\n" + text_out[anchor:]
    return "\n".join(out)


