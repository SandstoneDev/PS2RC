"""Hook bindings by name (written into the HLE build dir as hle_bind.h by the build script).

A game pack's hooks.def names the guest functions it hooks or traces - HOOK(addr, name), HOOK_OV(ov, addr, name),
TRACE(addr, name, flags), TRACE_OV(ov, addr, name, flags). The HLE sources never contain those addresses: they refer to
a hook by its name (hle.h):
    HLE_FN(name) / HLE_SCE(name)      defines the replacement of the guest function
    GUEST_FN(name) / GUEST_SCE(name)  the translated original (prepare_gen renamed it <symbol>__guest)
    HLE_CALL(name)                    the symbol calls go through (the replacement when hooked)
    HLE_ADDR(name)                    its guest address (0 when the pack does not bind the name)
    HLE_BOUND(name)                   1 when the pack binds the name, else 0 (usable in #if)
hle_bind.h maps each name to the generated C symbol:
    #define hle_fn_<name>    fn_<addr>          (ov<N>_fn_<addr> for an overlay function)
    #define hle_guest_<name> fn_<addr>__guest
    #define hle_addr_<name>  0x<addr>u
    #define HLE_BOUND_<name> 1
A name the sources use but the pack does not bind is compiled under a private symbol nobody calls
(hle_unbound_<name>); its guest original is hle_guest_unbound, which stops the run if ever reached - defined in
hle_bind.c next to hle_bind.h, written only when some unbound name's guest original is referenced.

    python3 bind.py HOOKS_DEF OUT_H SRC_DIR [SRC_DIR ...]     (files are rewritten only when their text changes)
"""
import os
import re
import sys

ENTRY = re.compile(r"^\s*(HOOK|TRACE)(_OV)?\(\s*(?:(\d+)\s*,\s*)?([0-9a-f]{8})\s*,\s*(\w+)", re.M)
USE = re.compile(r"\b(HLE_FN|HLE_SCE|GUEST_FN|GUEST_SCE|HLE_CALL|HLE_ADDR|HLE_BOUND)\(\s*(\w+)\s*\)")

UNBOUND_C = """/* hle_bind.c - generated by ps2rc bind.py: the guest original of a hook the game pack does not bind */
#include "hle.h"

void hle_guest_unbound(R5900Ctx *c)
{
    hle_die(c, "the guest original of a hook this game pack does not bind was called (hooks.def)");
}
"""


def read_hooks(path):
    """[(kind, overlay or 0, address, name)] in file order; names must be unique."""
    text = re.sub(r"/\*.*?\*/", "", open(path, encoding="utf-8").read(), flags=re.S)
    out, seen = [], {}
    for kind, ov, ovid, addr, name in ENTRY.findall(text):
        if name in seen:
            raise SystemExit("%s: hook name %s used twice (%s and %s)" % (path, name, seen[name], addr))
        seen[name] = addr
        out.append((kind, int(ovid) if ov else 0, int(addr, 16), name))
    return out


def used_names(dirs):
    """({names the sources use}, {names whose guest original they reference})."""
    names, guests = set(), set()
    for d in dirs:
        for f in sorted(os.listdir(d)):
            if not f.endswith((".c", ".h")) or f in ("hle_bind.h", "hle_bind.c"):
                continue
            text = open(os.path.join(d, f), encoding="utf-8", errors="replace").read()
            text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)        # comments
            text = re.sub(r"//[^\n]*", " ", text)
            text = re.sub(r"\\\r?\n", " ", text)                       # continued lines (macro bodies)
            for line in text.split("\n"):
                if line.lstrip().startswith("#"):                        # macro definitions use parameter names
                    continue
                for kind, name in USE.findall(line):
                    names.add(name)
                    if kind.startswith("GUEST"):
                        guests.add(name)
    return names, guests


def render(hooks, used):
    lines = ["/* hle_bind.h - generated by ps2rc bind.py from the game pack's hooks.def: hook name -> generated symbol",
             "   (see hle.h HLE_FN / GUEST_FN / HLE_ADDR / HLE_BOUND). Do not edit. */",
             "#ifndef HLE_BIND_H", "#define HLE_BIND_H", ""]
    bound = set()
    for _kind, ov, addr, name in hooks:
        sym = ("ov%d_" % ov if ov else "") + "fn_%08x" % addr
        bound.add(name)
        lines.append("#define hle_fn_%s %s" % (name, sym))
        lines.append("#define hle_guest_%s %s__guest" % (name, sym))
        lines.append("#define hle_addr_%s 0x%08xu" % (name, addr))
        lines.append("#define HLE_BOUND_%s 1" % name)
    unbound = sorted(used - bound)
    if unbound:
        lines += ["", "/* used by the HLE sources, not hooked by this pack */"]
    for name in unbound:
        lines.append("#define hle_fn_%s hle_unbound_%s" % (name, name))
        lines.append("#define hle_guest_%s hle_guest_unbound" % name)
        lines.append("#define hle_addr_%s 0u" % name)
        lines.append("#define HLE_BOUND_%s 0" % name)
    lines += ["", "#endif", ""]
    return "\n".join(lines), len(bound), len(unbound)


def write_if_changed(path, text):
    old = open(path, encoding="ascii").read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="ascii", newline="\n") as f:
            f.write(text)
    return old != text


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    hooks_def, out, dirs = argv[0], argv[1], argv[2:]
    hooks = read_hooks(hooks_def)
    used, guests = used_names(dirs)
    text, nb, nu = render(hooks, used)
    changed = write_if_changed(out, text)
    unbound_guests = guests - {h[3] for h in hooks}
    cfile = os.path.join(os.path.dirname(os.path.abspath(out)), "hle_bind.c")
    if unbound_guests:
        write_if_changed(cfile, UNBOUND_C)
    elif os.path.exists(cfile):
        os.remove(cfile)
    print("bind: %d hook names bound by the pack, %d names of the HLE sources unbound (%d guest originals)%s"
          % (nb, nu, len(unbound_guests), "" if changed else " (unchanged)"))


if __name__ == "__main__":
    main(sys.argv[1:])
